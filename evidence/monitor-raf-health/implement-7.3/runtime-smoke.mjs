import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { openStateStore } from '../../../src/state-store.ts';
import { runtimeHealthSummary } from '../../../src/health-summary-runtime.ts';
import { settleCommandState } from '../../../src/reminder-cli.ts';
import { loadEventCatalog } from '../../../src/event-catalog.ts';

const root = '/srv/dev/work/orchestrator';
const directory = mkdtempSync(join(tmpdir(), 'raf-summary-smoke-'));
let store = openStateStore(join(directory, 'state.sqlite'));
const checks = [];
try {
  const original = store.healthSummary.transaction(tx => structuredClone(tx.state));
  const old = new Date(Date.now() - 4 * 3600000).toISOString();
  store.healthSummary.transaction(tx => { tx.state.boundary = old; });
  store.recordHealthRefusal('SMOKE_REFUSAL', 'delivery');
  store.eventRepository.transaction(tx => tx.savePending({ key: 'smoke-event', event: { kind: 'raf.cpu-exceeded', id: original.rafInstanceId } }));
  store.startupContextDatabase.prepare('UPDATE raf_forced_close_metrics SET completed=completed+2 WHERE singleton=1').run();
  const fact = await runtimeHealthSummary(store, root).settle();
  assert.equal(fact.status, 'recorded');
  assert.equal(fact.summary.event.startedAt, old);
  assert.equal(fact.summary.event.delayed, true);
  assert.equal(fact.summary.event.forcedClose.value.completed, 2);
  assert.deepEqual(fact.summary.event.eventsByType.value, { 'raf.cpu-exceeded': 1 });
  assert.deepEqual(fact.summary.event.refusalsByCodeAndStage.value, { SMOKE_REFUSAL: { delivery: 1 } });
  assert.equal(fact.summary.event.queue.availability, 'unavailable');
  assert.equal(fact.summary.event.cpu.availability, 'unavailable');
  checks.push('SQLite aggregates, actual delayed period, force delta, explicit unavailable sources');
  const key = fact.summary.event.factKey;
  assert.equal(store.eventRepository.transaction(tx => tx.listPending().some(item => item.key === key)), false);
  assert.equal(store.healthSummary.claim(key, { token: 'offline', pid: process.pid, processStart: null }, new Date().toISOString(), () => true), undefined);
  checks.push('main offline retains fact; generic dispatch cannot delete an unacknowledged summary');
  store.close();
  store = openStateStore(join(directory, 'state.sqlite'));
  assert.equal((await runtimeHealthSummary(store, root).settle()).status, 'idle');
  assert.equal(store.healthSummary.transaction(tx => tx.state.rafInstanceId), original.rafInstanceId);
  assert.equal(store.sessionRepository.transaction(tx => tx.listPending().filter(item => item.event === 'raf.health-summary').length), 1);
  checks.push('restart preserves domain, boundary and one pending fact');
  store.sessionRepository.transaction(tx => tx.putSession({ runId: 'main-smoke', addressId: 'main', state: 'running', revision: 0 }));
  const at = new Date().toISOString();
  const owner = { token: 'first', pid: process.pid, processStart: null };
  assert.equal(store.healthSummary.claim(key, owner, at, () => true).recipientRunId, 'main-smoke');
  assert.equal(store.healthSummary.claim(key, { ...owner, token: 'second' }, at, () => true), undefined);
  store.healthSummary.complete(key, owner.token, false);
  assert.equal((await runtimeHealthSummary(store, root).read()).summary.delivery, 'pending');
  checks.push('delivery claim excludes a concurrent sender; rejected receipt remains pending');
  const requests = [];
  const ports = { store, orchestratorRoot: root, now: Date.now, nextReminderId: () => 'unused', catalog: loadEventCatalog(root),
    deliver: async (request, sender) => { requests.push({ request, sender }); return { accepted: true, receiptId: 'smoke-receipt' }; } };
  await settleCommandState(ports);
  await settleCommandState(ports);
  assert.equal(requests.length, 1);
  assert.equal(requests[0].request.to, 'main');
  assert.equal(requests[0].request.runId, 'main-smoke');
  assert.equal(requests[0].sender.kind, 'system');
  assert.equal((await runtimeHealthSummary(store, root).read()).summary.delivery, 'delivered');
  assert.equal(store.sessionRepository.transaction(tx => tx.listPending().some(item => item.id === key)), false);
  checks.push('existing settle sends one accepted system message fenced to current main and dispatches the fact');
  const before = store.healthSummary.transaction(tx => structuredClone(tx.state));
  assert.throws(() => store.healthSummary.transaction(tx => { tx.state.boundary = old; throw new Error('rollback'); }), /rollback/);
  assert.deepEqual(store.healthSummary.transaction(tx => tx.state), before);
  assert.equal(store.healthSummary.transaction(tx => tx.readSources(before.boundary, new Date().toISOString())).eventsByType.value['raf.health-summary'], 1);
  checks.push('transaction rollback preserves boundary; newly recorded summary counts only in the next period');
  console.log(JSON.stringify({ outcome: 'passed', checks, liveWorkerQA: false }, null, 2));
} finally { store.close(); rmSync(directory, { recursive: true, force: true }); }
